"""Generate kernel_overlay/.../ov64b40_tables.h from MediaTek OV64B imgsensor tables.

The FLIR Hadron EO's OV64B40 tables come from realme's GPL-2.0 Narzo 50 / 8i
(MIAMI, MT6781) kernel release, MCLK 24 MHz, MIPI D-PHY 4-lane:

  https://github.com/realme-kernel-opensource/realme_Narzo-50_8i-AndroidT-kernel-source
  commit 3c6fe902b4a5f223d7d95100b2c716a28c2aba3a
  drivers/misc/mediatek/imgsensor/src/common/v1/miami_ov64b/ov64b_Sensor_setting.h

usage: mtk_to_reg8.py <ov64b_Sensor_setting.h> <ov64b40_tables.h>

The source is parsed as data only. A 5 ms wait follows the software reset,
which MediaTek's burst writer gets away without.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]

# MediaTek table name -> (reg_8 table name, description)
TABLES = [
    ("addr_data_pair_init_ov64b2q", "ov64b40_global", "global init (MIAMI addr_data_pair_init_ov64b2q)"),
    ("addr_data_pair_crossTalk_ov64b2q", "ov64b40_crosstalk", "full-resolution remosaic crosstalk defaults (MIAMI addr_data_pair_crossTalk_ov64b2q)"),
    ("addr_data_pair_preview_ov64b2q", "ov64b40_mode_4624x3468", "4624x3468 @ 30 fps, 1699.2 Mbps/lane (MIAMI preview)"),
    ("addr_data_pair_custom2", "ov64b40_mode_3840x2160", "3840x2160 @ 60 fps, 2300 Mbps/lane (MIAMI custom2)"),
    ("addr_data_pair_hs_video_ov64b2q", "ov64b40_mode_2304x1296", "2304x1296 @ 120 fps, 1699.2 Mbps/lane (MIAMI hs_video)"),
    ("addr_data_pair_custom3", "ov64b40_mode_9248x6936", "9248x6936 @ 13.2 fps, 2400 Mbps/lane, full array remosaic (MIAMI custom3)"),
]

text = open(src, encoding="latin-1").read()
# strip comments
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
text = re.sub(r"//[^\n]*", "", text)

blocks = dict(re.findall(r"static\s+kal_uint16\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};", text, flags=re.S))

lines = ["/* SPDX-License-Identifier: GPL-2.0-only */",
         "/*",
         " * Generated by scripts/camera/mtk_to_reg8.py from the OV64B imgsensor tables in",
         " * realme's GPL-2.0 Narzo 50 / 8i (MIAMI) kernel release, commit 3c6fe902b4a5:",
         " * drivers/misc/mediatek/imgsensor/src/common/v1/miami_ov64b/ov64b_Sensor_setting.h",
         " * Copyright (C) 2015 MediaTek Inc. MCLK 24 MHz, MIPI D-PHY 4-lane.",
         " * Do not edit by hand; regenerate.",
         " */", ""]
for mtk, name, desc in TABLES:
    vals = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", blocks[mtk])]
    if len(vals) % 2:
        sys.exit(f"{mtk}: odd number of values")
    pairs = list(zip(vals[0::2], vals[1::2]))
    for a, v in pairs:
        if a > 0xFFFF or v > 0xFF:
            sys.exit(f"{mtk}: bad pair {a:#x},{v:#x}")
    lines.append(f"/* {desc}: {len(pairs)} writes */")
    lines.append(f"static const ov64b40_reg {name}[] = {{")
    for a, v in pairs:
        lines.append(f"\t{{0x{a:04x}, 0x{v:02x}}},")
        if a == 0x0103 and v == 0x01:
            lines.append("\t{OV64B40_TABLE_WAIT_MS, 5},")
    lines.append("\t{OV64B40_TABLE_END, 0x00}")
    lines.append("};")
    lines.append("")
    print(f"{name}: {len(pairs)} writes")
open(out, "w").write("\n".join(lines))
